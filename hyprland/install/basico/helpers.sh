#!/bin/bash
# ─── Colores ──────────────────────────────────────────────────────────────────
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
BOLD='\033[1m'
DIM='\033[2m'
NC='\033[0m'

# ─── Helpers ──────────────────────────────────────────────────────────────────
step()    { echo -e "\n${BLUE}${BOLD}▶  $1${NC}"; }
info()    { echo -e "   ${DIM}→  $1${NC}"; }
ok()      { echo -e "   ${GREEN}✔  $1${NC}"; }
warn()    { echo -e "   ${YELLOW}⚠  $1${NC}"; }
die()     { echo -e "\n   ${RED}ERROR  $1${NC}\n" >&2; exit 1; }
header()  {
    echo -e "\n${CYAN}┌────────────────────────────────────────────────────────────────────────────┐${NC}"
    printf "${CYAN}│ %-74s │${NC}\n" "$1"
    echo -e "${CYAN}└────────────────────────────────────────────────────────────────────────────┘${NC}"
}
